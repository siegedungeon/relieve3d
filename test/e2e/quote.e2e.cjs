const fs = require('node:fs');
const path = require('node:path');
const { PNG } = require('pngjs');

module.exports = async ({ win, run, shot, wait }) => {
  const out = process.env.E2E_DIR, exportsDir = process.env.R3D_AUTOSAVE_DIR, errors = [];
  win.webContents.on('console-message', e => {
    if ((e.level === 'error' || e.level >= 3) && !/disk_cache|WebGLProgram/.test(e.message)) errors.push(e.message);
  });
  const ok = (value, message) => { console.log('[e2e]', value ? 'ok  ' : 'FAIL', message); if (!value) throw new Error(message); };
  const read = async expression => JSON.parse(await run(`JSON.stringify(${expression})`));
  const ready = async () => {
    for (let i = 0; i < 1200; i++) {
      if (await run('!!window.__r3d?.quote?.library && !window.__r3d.quote.busy')) return;
      await wait(50);
    }
    throw new Error('Quotation UI operation did not finish.');
  };
  const click = async selector => {
    await run(`(()=>{const b=document.querySelector(${JSON.stringify('#quote ' + selector)});if(!b||b.disabled)throw new Error('Unavailable control: '+${JSON.stringify(selector)});b.click();})()`);
    await ready();
  };
  const tab = name => click(`[data-tab="${name}"]`);
  const set = async (field, value, attr = 'field') => {
    await run(`(()=>{const el=document.querySelector('#quote [data-${attr}="${field}"]');if(!el||el.disabled)throw new Error('Unavailable field: ${field}');
      if(el.type==='checkbox')el.checked=${JSON.stringify(value)};else el.value=${JSON.stringify(String(value))};
      el.dispatchEvent(new Event('input',{bubbles:true}));el.dispatchEvent(new Event('change',{bubbles:true}));})()`);
    await ready();
  };
  const capture = async name => { win.show(); win.focus(); await wait(250); await shot(path.join(out, name + '.png')); };
  win.setSize(1500, 1000);
  ok(await run(`!!document.querySelector('#homeGridBusiness [data-mod="quote"]')`), 'quotation module has its own business section');
  await run(`document.querySelector('#homeGridBusiness [data-mod="quote"]').click()`);
  await ready();
  ok(await run(`window.__r3d.quote.tab==='quick'&&!document.querySelector('#quote [data-field="customer.name"]')&&!document.querySelector('#quote [data-action="issue"]')`), 'default entry is a quick calculator without client or commercial issuance fields');
  ok(await run(`window.__r3d.quote.result===null&&document.querySelector('#quote [data-result-error]').hidden`), 'new quick calculation starts empty, without fabricated measurements or a validation error');
  await set('minutes', '43', 'quick-duration'); await set('materials.0.grams', '10');
  ok(await run(`window.__r3d.quote.result.totalCost==='2262.17'&&window.__r3d.quote.result.unitPrice==='4000.00'&&window.__r3d.quote.result.profit==='1737.83'`), 'two measured values immediately produce cost, suggested price and estimated profit');
  ok(await run(`!window.__r3d.quote.input.labor.length&&!window.__r3d.quote.input.accessories.length&&window.__r3d.quote.input.packaging.cost==='0'`), 'quick calculation does not silently include finishing, rings or packaging');
  await capture('quote_00_quick');
  await set('hours', '-1', 'quick-duration');
  ok(await run(`window.__r3d.quote.result===null&&!document.querySelector('#quote [data-result-error]').hidden`), 'invalid quick duration never leaves stale prices visible');
  await set('hours', '0', 'quick-duration');
  await set('materials.0.grams', '10.5');
  ok(await run(`window.__r3d.quote.result.totalCost==='2312.57'`), 'quick filament consumption accepts decimals');
  await set('materials.0.grams', '10');
  await tab('wholesale');
  await click('[data-action="tier"][data-quantity="20"]');
  ok(await run(`window.__r3d.quote.tab==='quick'&&window.__r3d.quote.result.quantity===20&&window.__r3d.quote.result.unitPrice==='3500.00'`), 'wholesale selection returns to the quick calculation without asking for a client');
  await set('print.mode', 'batch'); await set('quantity', '10');
  await set('hours', '41', 'quick-duration'); await set('minutes', '0', 'quick-duration'); await set('materials.0.grams', '500');
  ok(await run(`window.__r3d.quote.input.print.minutes==='2460'&&window.__r3d.quote.result.totalCost==='122150.00'`), 'quick plate calculation charges measured hours and grams only once');
  await set('quantity', '20');
  ok(await run(`window.__r3d.quote.result.totalCost==='122150.00'&&window.__r3d.quote.result.production.batches===1`), 'changing the number of pieces on a measured plate does not multiply plate consumption');
  await set('print.mode', 'unit'); await set('quantity', '1'); await set('hours', '0', 'quick-duration');
  await set('minutes', '43', 'quick-duration'); await set('materials.0.grams', '10');
  await click('[data-action="save"]');
  const quickId = await read('window.__r3d.quote.record.id');
  ok(await run(`window.__r3d.quote.record.status==='draft'&&window.__r3d.quote.record.input.customer.name===''&&window.__r3d.quote.record.input.entryMode==='quick'`), 'quick calculation can be saved with no customer information');
  await tab('history'); await click(`[data-action="load"][data-id="${quickId}"]`);
  ok(await run(`window.__r3d.quote.tab==='quick'&&window.__r3d.quote.result.totalCost==='2262.17'`), 'saved anonymous calculation reopens directly in quick mode');
  win.setContentSize(390, 844); await wait(400);
  ok(await run(`document.querySelector('#quote .q-page').scrollWidth<=document.querySelector('#quote .q-page').clientWidth+2&&document.querySelector('#quote .q-form').getBoundingClientRect().top<document.querySelector('#quote [data-summary]').getBoundingClientRect().top`), 'narrow quick view keeps the input fields first and has no horizontal page overflow');
  await capture('quote_00_quick_mobile'); win.setSize(1500, 1000); await wait(200);
  await click('[data-section="quick-extras"] > summary');
  await click('[data-action="ring"][data-kind="standard"]');
  ok(await run(`window.__r3d.quote.result.totalCost==='3162.17'`), 'optional ring adds exactly its configured cost');
  await click('[data-action="remove"][data-list="accessories"][data-index="0"]');
  ok(await run(`window.__r3d.quote.result.totalCost==='2262.17'`), 'removing the optional ring restores the base estimate');
  await click('[data-action="ring"][data-kind="standard"]'); await click('[data-action="quick-labor"]'); await click('[data-action="quick-package"]');
  ok(await run(`window.__r3d.quote.result.totalCost==='8662.17'`), 'finishing and packaging are charged only after explicitly adding them');
  await click('[data-summary] [data-tab="quote"]');
  ok(await run(`window.__r3d.quote.input.entryMode==='full'&&window.__r3d.quote.record.id===${JSON.stringify(quickId)}&&window.__r3d.quote.result.totalCost==='8662.17'`), 'full quotation handoff preserves the same draft, measurements, optional charges and total');
  ok(await run(`!document.getElementById('quote').hidden && window.__r3d.quote.result.unitPrice==='13500.00'`), 'real module loads persisted defaults and calculates the initial price');
  await set('customer.name', 'Cliente de prueba E2E');
  await set('customer.contact', 'Contacto de demostración');
  const pastDate = new Date(Date.now() - 3 * 86400000).toISOString().slice(0, 10);
  await set('date', pastDate);
  await set('internalNotes', 'PRIVATE_E2E_COST_MARKER');
  await set('quantity', '130');
  await set('strategy', 'manual'); await set('manualPrice', '6000');
  ok(await run(`window.__r3d.quote.result.total==='780000.00' && window.__r3d.quote.result.profit==='-346081.67'`), '130 at COP 6000 exposes the real loss with the ring and per-unit labor');
  ok(await run(`document.querySelector('#quote [data-action="issue"]').disabled`), 'cannot issue a below-minimum quote');
  await capture('quote_01_loss');
  await set('strategy', 'markup'); await set('target', '55');
  await set('quantity', '0');
  ok(await run(`window.__r3d.quote.result===null && !document.querySelector('#quote [data-result-error]').hidden`), 'invalid quantity clears stale totals');
  await set('quantity', '130');
  ok(await run(`!document.querySelector('#quote [data-action="save"]').disabled`), 'valid input restores saving');

  const before = await read('window.__r3d.quote.result.totalCost');
  await click('[data-action="add-accessory"]');
  await set('accessories.1.name', 'Imán adicional'); await set('accessories.1.cost', '100'); await set('accessories.1.quantity', '2');
  ok(await run(`Number(window.__r3d.quote.result.totalCost)-Number(${JSON.stringify(before)})===26000`), 'extra accessories are charged per unit and update the real result');
  await click('[data-action="remove"][data-list="accessories"][data-index="1"]');
  ok(await run(`window.__r3d.quote.result.totalCost===${JSON.stringify(before)}`), 'removing an accessory restores the original exact cost');
  await capture('quote_02_costs');
  await tab('wholesale');
  ok(await run(`window.__r3d.quote.volumeResults.map(r=>r.quantity).join(',')==='1,20,50,100,130,200'`), 'quantity table includes retail, 20, 50, 100 and more than 100');
  ok(await run(`window.__r3d.quote.volumeResults.every(r=>r.canIssue&&Number(r.margin)>=20)`), 'volume recommendations respect the minimum margin');
  await capture('quote_03_wholesale');
  await tab('scenarios');
  ok(await run(`document.querySelectorAll('#quote .q-scenarios article').length===4`), 'four editable-rule scenarios are rendered');
  await capture('quote_04_scenarios');
  await click('[data-action="scenario"][data-index="2"]');
  await tab('compare');
  await set('quality', true, 'compare');
  ok(await run(`document.querySelector('#quote [data-comparison]').textContent.includes('optimizada')`), 'comparison recommends the optimized design at the same sale price after confirming quality');
  await capture('quote_05_comparison');

  await tab('quote'); await set('strategy', 'margin'); await set('target', '40');
  await tab('wholesale');
  const selectedPrice = await read('window.__r3d.quote.volumeResults.find(r=>r.quantity===20).unitPrice');
  await click('[data-action="tier"][data-quantity="20"]');
  ok(await run(`window.__r3d.quote.input.strategy==='margin'&&window.__r3d.quote.result.unitPrice===${JSON.stringify(selectedPrice)}`), 'choosing a wholesale quantity preserves the strategy and price actually displayed');
  await set('quantity', '130'); await set('strategy', 'markup'); await set('target', '55');
  await tab('quote'); await set('printers.0.copies', '2');
  ok(await run(`Number(window.__r3d.quote.result.production.calendarHours)<Number(window.__r3d.quote.result.production.machineHours)`), 'parallel schedule distinguishes calendar and accumulated machine hours');
  await set('print.capacity', '10'); await set('print.unitsPerBatch', '10'); await set('quantity', '13');
  await set('print.mode', 'batch'); await set('print.minutes', '2460'); await set('materials.0.grams', '500');
  ok(await run(`window.__r3d.quote.result.production.fullBatches===1&&window.__r3d.quote.result.production.partialUnits===3&&window.__r3d.quote.result.warnings.some(w=>w.includes('parcial aproximada'))`), 'whole and incomplete plates use the explicit batch modality');
  await set('print.partialMethod', 'actual'); await set('print.partialMinutes', '1000'); await set('materials.0.partialGrams', '170');
  ok(await run(`window.__r3d.quote.result.production.usage[0].baseGrams==='670'`), 'real partial-plate measurements replace proportional estimates');
  await tab('production'); await capture('quote_06_production');

  await tab('quote');
  await set('print.mode', 'unit'); await set('print.minutes', '43'); await set('print.unitsPerBatch', '1'); await set('print.partialMethod', 'estimate');
  await set('materials.0.grams', '10'); await set('quantity', '130'); await set('printers.0.copies', '1');
  await click('[data-action="save"]');
  ok(await run(`window.__r3d.quote.record.status==='draft'&&window.__r3d.quote.record.versions.length===0`), 'draft is persisted through the actual IPC service');
  await click('[data-action="issue"]');
  const number = await read('window.__r3d.quote.record.number');
  const id = await read('window.__r3d.quote.record.id');
  const snapshot = await read('JSON.stringify(window.__r3d.quote.record.versions[0])');
  ok(await run(`window.__r3d.quote.record.status==='sent'&&window.__r3d.quote.record.versions.length===1`), 'issuing creates an immutable commercial snapshot');
  await click('[data-action="preview"]'); await capture('quote_07_commercial');
  ok(await run(`(()=>{const html=document.querySelector('#quote iframe').srcdoc;return html.includes('Cliente de prueba E2E')&&!html.includes('PRIVATE_E2E_COST_MARKER')&&!html.includes('Desglose interno');})()`), 'commercial preview contains the client information but no internal fields');
  await click('[data-action="close-preview"]');
  for (const format of ['pdf', 'png', 'compact', 'html']) await click(`[data-action="export"][data-format="${format}"]`);
  const pdf = fs.readFileSync(path.join(exportsDir, `${number}_v1.pdf`));
  ok(pdf.subarray(0, 5).toString() === '%PDF-' && pdf.length > 1000, 'real Electron PDF export produces a populated document');
  for (const type of ['png', 'compact']) {
    const png = PNG.sync.read(fs.readFileSync(path.join(exportsDir, `${number}_v1_${type}.png`)));
    let ink = 0; for (let i = 0; i < png.data.length; i += 4) if (png.data[i] < 200 || png.data[i + 1] < 200 || png.data[i + 2] < 200) ink++;
    ok(png.width === (type === 'compact' ? 1080 : 900) && ink > 10000, `${type} export has the expected width and visible document content`);
  }
  const html = fs.readFileSync(path.join(exportsDir, `${number}_v1.html`), 'utf8');
  ok(!html.includes('PRIVATE_E2E_COST_MARKER') && html.includes('Pabonitas'), 'printable HTML is also commercial-only');
  ok(await run(`(async()=>{const c=window.__r3d.quote,r=await window.api.quoteExport({id:c.record.id,version:1,format:'text'});return r.text.includes('TOTAL')&&!r.text.includes('PRIVATE_E2E_COST_MARKER');})()`), 'copy-ready text is built from the same issued snapshot');

  await tab('settings'); await set('materials.0.kgCost', '180000', 'config');
  await click('[data-action="home"]');
  await run(`window.__r3d.enterModule('quote')`); await ready();
  ok(await run(`window.__r3d.quote.settingsDirty&&window.__r3d.quote.settings.materials[0].kgCost==='180000'`), 'unsaved settings survive leaving and reopening the module');
  await click('[data-action="save-settings"]');
  ok(await run(`window.__r3d.quote.library.configs.length===2&&window.__r3d.quote.configVersion===1`), 'new cost settings do not silently reprice the current quote');
  await tab('history'); await capture('quote_08_history');
  await click(`[data-action="load"][data-id="${id}"][data-version="1"]`);
  ok(await run(`JSON.stringify(window.__r3d.quote.record.versions[0])===${JSON.stringify(snapshot)}&&window.__r3d.quote.readOnly`), 'historical issued version reopens read-only with its original prices');
  ok(await run(`document.querySelector('#quote [data-field="quantity"]').disabled`), 'historical inputs cannot be edited in place');
  ok(await run(`(()=>{const q=window.__r3d.quote,c=q.config,expected=q.record.versions[0].result.totalCost;
    try{q.config=structuredClone(c);q.config.printers[0].hourlyRate='99999';q.updateResults();return q.result.totalCost===expected;}
    finally{q.config=c;q.updateResults();}})()`), 'read-only summary uses saved results instead of recalculating historical commitments');
  await tab('history');
  await click(`[data-action="load"][data-id="${id}"]:not([data-version])`);
  ok(await run(`!window.__r3d.quote.readOnly`), 'current sent quote can still be revised before acceptance');
  await tab('history');
  await click(`[data-action="status"][data-id="${id}"][data-status="accepted"]`);
  ok(await run(`window.__r3d.quote.readOnly`), 'accepting immediately locks the currently open quote');
  await click(`[data-action="status"][data-id="${id}"][data-status="converted"]`);
  ok(await run(`window.__r3d.quote.library.orders.length===1`), 'accepted quote converts into a local order reference without duplicating the sale');
  await run(`for(const [key,value] of [['cost','1000000'],['hours','94'],['grams','1500']])document.querySelector('#quote [data-actual="'+key+'"][data-id="${id}"]').value=value;`);
  await click(`[data-action="actuals"][data-id="${id}"]`);
  await tab('analytics');
  ok(await run(`document.querySelector('#quote [data-history]').textContent.includes('Estimado contra real')&&window.__r3d.quote.library.quotes[0].actuals.totalCost==='1000000'`), 'analytics includes committed sales and actual-versus-estimated costs');
  await capture('quote_09_analytics');

  await tab('quote'); win.setContentSize(390, 844); await wait(400);
  ok(await run(`window.innerWidth<=410&&document.querySelector('#quote .q-page').scrollWidth<=document.querySelector('#quote .q-page').clientWidth+2`), 'mobile-width form fits without horizontal page overflow');
  ok(await run(`!!document.querySelector('#quote [data-summary-detail="costs"]')`), 'mobile view keeps the internal breakdown accessible in a collapsible section');
  await capture('quote_10_mobile');
  await tab('wholesale'); await capture('quote_11_mobile_table');
  await click('[data-action="duplicate"]');
  ok(await run(`!window.__r3d.quote.record&&!window.__r3d.quote.readOnly&&window.__r3d.quote.configVersion===2`), 'duplicating creates an editable quote with current costs, not a modified historical version');
  ok(await run(`window.__r3d.quote.input.date!==${JSON.stringify(pastDate)}&&window.__r3d.quote.input.deliveryDate===''`), 'duplicate renews its date instead of reusing the historical commitment');
  await click('[data-action="save"]');
  await click('[data-action="home"]'); await wait(200);
  ok(await run(`!document.getElementById('home').hidden&&document.getElementById('quote').hidden`), 'home navigation hides the quotation module');
  ok(win.getMinimumSize()[0] === 1100, 'leaving restores the existing 3D workspace minimum size');
  await new Promise(resolve => { win.webContents.once('did-finish-load', resolve); win.reload(); });
  for (let i = 0; i < 200 && !(await run('!!window.__r3d?.quote')); i++) await wait(50);
  await run(`window.__r3d.enterModule('quote')`); await ready();
  ok(await run(`window.__r3d.quote.library.quotes.length===2&&window.__r3d.quote.library.quotes[0].versions.length===1`), 'full renderer restart reloads the original snapshot and duplicated draft from disk');
  const stored = JSON.parse(fs.readFileSync(path.join(process.env.R3D_QUOTE_TEST_DIR, 'quotations-v1.json')));
  ok(stored.quotes[0].versions[0].configSnapshot.materials[0].kgCost === '90000' && stored.configs[1].value.materials[0].kgCost === '180000', 'disk persistence contains both immutable historical and new configurations');
  ok(errors.length === 0, `no renderer errors: ${errors.join(' | ')}`);
  console.log('[e2e] done');
};
